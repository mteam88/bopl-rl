"""Does ability id N mean the same ability in the Rust sim and in the C# oracle?

Both backends report `bopl_rl_ability_count() == 39`, and that count is the ONLY
cross-backend ability check anywhere in the tree (rust_ab/null_ability_ab.c:26,
puffer/bopl_puffer.h:848). Identity -- that index 7 is Gust on both sides, not
merely that both have 39 entries -- is asserted nowhere: `bopl_rl_catalog_hash`
is a hard-coded sentinel on the Rust side (mod.rs SOURCE_HASH/CATALOG_HASH), so
comparing the two hashes directly is meaningless and nothing does it.

The oracle's hash, though, is real. ReplaySession.CatalogHash is

    sha256("\\n".join(f"{i}:{sprite.name}:{sprite.associatedGameObject?.name}"))

over the live `SteamManager.instance.abilityIcons.sprites` list, and the Rust
backend's ability table is generated by tools/extract_rollout_data.py from
native/data/ability-coverage.json bound POSITIONALLY to the same exported asset
(`sprites.Array.data[id]`) without ever checking the binding. So recomputing that
formula from the checked-in table and matching it against the oracle's live hash
does test the seam: it passes only if the table is index-for-index the catalogue
the oracle is actually playing with.

    python catalog_parity.py <oracle.so>

A negative control runs too: two perturbations of the table (a swap of two
neighbouring abilities, and a rename) must both produce a DIFFERENT hash. Without
it a checker that hashed, say, a constant would "pass" for ever -- the failure
mode this repo has already shipped three times.
"""
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent


def catalog_rows():
    """The checked-in ability table, in the order that defines the public RL id."""
    catalog = json.loads((ROOT / 'native/data/ability-coverage.json').read_text())['abilities']
    assets = json.loads((ROOT / 'native/reference-export/assets.json').read_text())
    rows = []
    for expected, entry in enumerate(catalog):
        if entry['id'] != expected:
            raise SystemExit(f'ability coverage is not dense at {expected}: {entry}')
        prefab = entry.get('prefab_guid')
        rows.append((entry['id'], entry['name'],
                     assets[prefab]['data']['name'] if prefab else ''))
    return rows


def digest(rows):
    """ReplaySession.CatalogHash, recomputed: sha256 of index:name:prefabName lines."""
    return hashlib.sha256('\n'.join(f'{i}:{n}:{p}' for i, n, p in rows).encode()).hexdigest()


def oracle_catalog_hash(game):
    out = subprocess.run([sys.executable, str(HERE / 'game_abi.py'), '--one', game,
                          str(ROOT / 'native/artifacts/rl/logs/game-abi')],
                         capture_output=True, text=True, cwd=str(HERE))
    if out.returncode:
        raise SystemExit(f'{game}: {out.stdout}{out.stderr}')
    info = json.loads(out.stdout.strip().splitlines()[-1])
    return info['catalog_hash'], info['ability_count']


def rust_constants():
    """ABILITY_* ids compiled into the Rust backend (rollout/mod.rs)."""
    text = (ROOT / 'native/src/rollout/mod.rs').read_text()
    return {m.group(1): int(m.group(2)) for m in
            re.finditer(r'pub const ABILITY_([A-Z0-9_]+):\s*u32\s*=\s*(\d+)', text)}


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    game = sys.argv[1]
    rows = catalog_rows()
    mine = digest(rows)
    theirs, count = oracle_catalog_hash(game)

    # Negative controls: the hash must actually depend on the catalogue's content
    # and on its order, or "match" would prove nothing.
    swapped = list(rows); swapped[6], swapped[7] = swapped[7], swapped[6]
    swapped = [(i, n, p) for i, (_, n, p) in enumerate(swapped)]
    renamed = [(i, n + 'X' if i == 19 else n, p) for i, n, p in rows]
    controls = {'order (swap ids 6/7)': digest(swapped), 'name (rename id 19)': digest(renamed)}
    blind = [k for k, v in controls.items() if v == mine]

    print(f'checked-in table:   {len(rows)} abilities, dense 0..{len(rows)-1}')
    print(f'recomputed hash:    {mine}')
    print(f'oracle live hash:   {theirs}   (bopl_rl_ability_count={count})')
    for name, value in controls.items():
        print(f'negative control {name:24s} -> {value[:16]}...  {"BLIND" if value == mine else "differs"}')

    # The compiled ids are a second, independent binding: extract_rollout_data.py
    # generates the data tables, but rollout/mod.rs hard-codes ABILITY_* by hand.
    # Constants name the ability's first word ("BLINK" for "Blink gun"), so match
    # on a normalised prefix; ABILITY_COUNT is a width, not an id.
    def norm(text):
        return re.sub(r'[^a-z0-9]', '', text.lower())
    constants = {k: v for k, v in rust_constants().items() if k != 'COUNT'}
    matched, bad = {}, {}
    for key, value in constants.items():
        hit = [i for i, name, _ in rows if norm(name).startswith(norm(key))]
        if not hit:
            continue
        (matched if value in hit else bad)[key] = value
    print(f'rust ABILITY_* constants: {len(constants)} ids, {len(matched)} confirmed against the '
          f'table by name, {len(constants) - len(matched) - len(bad)} unmatched name, {len(bad)} CONTRADICTED')
    for k, v in bad.items():
        print(f'  ABILITY_{k} = {v} but the table calls id {v} '
              f'{rows[v][1] if v < len(rows) else "out of range"!r}')

    if blind:
        raise SystemExit(f'negative control did not move the hash ({blind}): this check proves nothing')
    if len(rows) != count:
        raise SystemExit(f'ability count differs: table {len(rows)} vs oracle {count}')
    if mine != theirs:
        raise SystemExit('CATALOGUE MISMATCH: the checked-in ability table is not the catalogue '
                         'the oracle plays with; ability ids do not mean the same thing in the two backends')
    if bad:
        raise SystemExit('Rust ABILITY_* constants contradict the table')
    print('\nOK: ability id N is the same ability in both backends '
          '(oracle live catalogue == checked-in table, order and names included)')


if __name__ == '__main__':
    main()
