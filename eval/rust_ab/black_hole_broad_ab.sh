#!/bin/sh
set -eu

if [ "$#" -ne 2 ]; then
    echo "usage: $0 <BoplSimNative.so> <libbopl_sim.so>" >&2
    exit 2
fi

reference=$1
rust=$2
project=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT HUP INT TERM

# One broad Black Hole gate over grounded/airborne form motion, persistent
# growth and wall/player consumption, Arrow attraction and consumption, stock
# reconstruction, Time Stop freeze/restoration, and protected-team timing.
for scenario in black_hole_ability_ab black_hole_arrow_ab time_stop_black_hole_ab
do
    cc -O2 -I"$project/sim/abi" -o "$tmp/$scenario" \
        "$project/eval/rust_ab/$scenario.c" "$project/sim/abi/bopl_rl.c" -ldl -lm
    (cd "$project" && "$tmp/$scenario" "$reference" "$rust")
done

echo "BLACK_HOLE_BROAD_GOLDEN_OK scenarios=3"
