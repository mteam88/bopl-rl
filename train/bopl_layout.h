/* Observation layout v3, shared by the environment, CPU/CUDA set encoders,
 * evaluator and Python checkpoint tooling. Ability ids are exact integer-valued
 * floats in the final column of slot/entity rows and are used only to gather
 * E[id]; their projection widths deliberately exclude that column. */
#ifndef BOPL_LAYOUT_H
#define BOPL_LAYOUT_H

#define BOPL_ARCHITECTURE "bopl-set-mingru-v3"

enum {
    BOPL_ABILITY_COUNT=39,
    BOPL_EMBEDDING_IDS=BOPL_ABILITY_COUNT+1,
    BOPL_OBS_PREFIX=66,
    BOPL_SELF_FEATURES=20,
    BOPL_OBS_PLAYERS=6, BOPL_PLAYER_FEATURES=20,
    BOPL_OBS_SLOTS=24, BOPL_SLOT_FEATURES=14,
    BOPL_OBS_ENTITIES=64, BOPL_ENTITY_FEATURES=34,
    BOPL_OBS_SLIMES=32, BOPL_SLIME_FEATURES=30,
    BOPL_PREVIOUS_FEATURES=12,
    /* Kept as a source-compatible name for research_layout's third field. */
    BOPL_ABILITY_FEATURES=BOPL_SLOT_FEATURES,
    BOPL_OBS_SELF_OFFSET=BOPL_OBS_PREFIX,
    BOPL_OBS_PLAYER_OFFSET=BOPL_OBS_SELF_OFFSET+BOPL_SELF_FEATURES,
    BOPL_OBS_SLOT_OFFSET=BOPL_OBS_PLAYER_OFFSET+BOPL_OBS_PLAYERS*BOPL_PLAYER_FEATURES,
    BOPL_OBS_ENTITY_OFFSET=BOPL_OBS_SLOT_OFFSET+BOPL_OBS_SLOTS*BOPL_SLOT_FEATURES,
    BOPL_OBS_SLIME_OFFSET=BOPL_OBS_ENTITY_OFFSET+BOPL_OBS_ENTITIES*BOPL_ENTITY_FEATURES,
    BOPL_OBS_PREVIOUS_OFFSET=BOPL_OBS_SLIME_OFFSET+BOPL_OBS_SLIMES*BOPL_SLIME_FEATURES,
    BOPL_OBS_SIZE=BOPL_OBS_PREVIOUS_OFFSET+BOPL_PREVIOUS_FEATURES,
    BOPL_SLOT_ABILITY_ID=BOPL_SLOT_FEATURES-1,
    BOPL_ENTITY_ABILITY_ID=BOPL_ENTITY_FEATURES-1,
    BOPL_COUNT_SCALE=64,
    BOPL_TIMER_TICKS=600
};

/* Action heads are unchanged from v2: independent aim, buttons and hold. */
enum { BOPL_ACT_AIM=256, BOPL_ACT_BUTTONS=16, BOPL_ACT_HOLD=5, BOPL_NUM_ATNS=3,
       BOPL_HOLD_MAX=16, BOPL_LOGITS=BOPL_ACT_AIM+BOPL_ACT_BUTTONS+BOPL_ACT_HOLD,
       BOPL_DECODER=BOPL_LOGITS+1 };
static const int BOPL_HOLD_LENGTHS[BOPL_ACT_HOLD]={1, 2, 4, 8, 16};
enum { BOPL_BUTTON_JUMP=0, BOPL_BUTTON_DASH=1, BOPL_BUTTON_ARROW=2, BOPL_BUTTON_PLATFORM=3 };
enum { BOPL_ABILITY_ACTIVE=8, BOPL_ABILITY_CHARGE_SHIFT=4,
       BOPL_ABILITY_CHARGE_MASK=7, BOPL_ABILITY_FIRED=0x80 };

#endif
